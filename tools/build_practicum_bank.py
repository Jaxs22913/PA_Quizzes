"""Generate practicum-bank.js — every identifiable structure across both
practicum exams, with the geometry needed to draw it on its plate.

This is what practicum-builder.html picks from. The atlas
(practicum-atlas-data.js) already knows the grouping (exam / section / region /
title) but carries no structures, and each quiz page carries structures but no
grouping, so this joins the two on the slug.

Per plate it keeps the things that MUST travel with the item or the marker
renders wrong on a mixed-plate exam:
  * w/h — the viewBox that frames the plate;
  * ak  — the arrow scale, w/3168 for that plate. These run from ~100 to 3168
          user units, so one fixed scale cannot serve them all;
  * the reveal text's x/y/anchor/size, taken from the plate's own pre-placed
    reveal element so the authored placement is preserved.

Keys are short because this ships as one file to the browser.

Usage: python3 tools/build_practicum_bank.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ATLAS = os.path.join(ROOT, "practicum-atlas-data.js")
OUT = os.path.join(ROOT, "practicum-bank.js")


def load_atlas():
    s = open(ATLAS, encoding="utf-8").read()
    return json.loads(s[s.index("["):s.rindex(";")])


def parse_quiz(path):
    """Structures + plate geometry from one practicum quiz page."""
    s = open(path, encoding="utf-8").read()

    m = re.search(r"const ITEMS = (\[.*?\]);", s, re.S)
    if not m:
        return None
    items = json.loads(m.group(1))

    svg = re.search(r'<svg viewBox="0 0 ([\d.]+) ([\d.]+)"[^>]*>\s*<image href="([^"]+)"', s)
    if not svg:
        return None
    w, h, img = float(svg.group(1)), float(svg.group(2)), svg.group(3)

    ak = re.search(r"const AK = ([\d.]+);", s)
    ak = float(ak.group(1)) if ak else round(w / 3168, 4)

    fs = re.search(r"\.reveal-text\{font-size:([\d.]+)px", s)
    font = float(fs.group(1)) if fs else round(max(6.0, w * 0.021), 1)

    reveals = {}
    for r in re.finditer(r'<text id="reveal-(\d+)" x="(-?[\d.]+)" y="(-?[\d.]+)" text-anchor="(\w+)"', s):
        reveals[int(r.group(1))] = (float(r.group(2)), float(r.group(3)), r.group(4))

    out = []
    for it in items:
        rx, ry, ra = reveals.get(it.get("num"), (None, None, None))
        if rx is None:
            off = w * 0.08
            rx = it["cx"] + off if it["side"] == "left" else it["cx"] - off
            ry = it["cy"] + font * 0.35
            ra = "start" if it["side"] == "left" else "end"
        out.append({"a": it["answer"], "x": it["cx"], "y": it["cy"], "s": it["side"],
                    "rx": rx, "ry": ry, "ra": ra})
    return {"img": img, "w": w, "h": h, "ak": ak, "fs": font, "items": out}


def main():
    plates = []
    skipped = []
    for entry in load_atlas():
        quiz = os.path.join(ROOT, entry["folder"], entry["slug"] + "-quiz.html")
        if not os.path.exists(quiz):
            skipped.append(entry["slug"]); continue
        got = parse_quiz(quiz)
        if not got or not got["items"]:
            skipped.append(entry["slug"]); continue
        plates.append({
            "slug": entry["slug"],
            "exam": entry["exam"],
            "sec": entry["section"],
            "reg": entry.get("region") or "",
            "title": entry["title"],
            # the builder page sits at the site root, so images need the folder
            "img": entry["folder"].replace(" ", "%20") + "/" + got["img"],
            "w": got["w"], "h": got["h"], "ak": got["ak"], "fs": got["fs"],
            "items": got["items"],
        })

    body = json.dumps(plates, ensure_ascii=False, separators=(",", ":"))
    open(OUT, "w", encoding="utf-8").write(
        "/* AUTO-GENERATED by tools/build_practicum_bank.py -- DO NOT EDIT BY HAND.\n"
        "   Every identifiable structure across both practicum exams, with the\n"
        "   per-plate geometry a mixed-plate exam needs. Consumed by\n"
        "   practicum-builder.html. */\n"
        "window.PRACTICUM_BANK = " + body + ";\n")

    total = sum(len(p["items"]) for p in plates)
    kb = os.path.getsize(OUT) / 1024
    print(f"practicum-bank.js: {len(plates)} plates, {total} structures, {kb:.0f} KB")
    if skipped:
        print(f"  skipped {len(skipped)} atlas entries with no quiz/items: {skipped[:4]}")
    by_exam = {}
    for p in plates:
        k = (p["exam"], p["sec"])
        by_exam[k] = by_exam.get(k, 0) + len(p["items"])
    for k in sorted(by_exam):
        print(f"    {k[0]:<18} {k[1]:<22} {by_exam[k]:>5} structures")


if __name__ == "__main__":
    main()
