#!/usr/bin/env python3
"""Build the Practicum Atlas: pick a group of study pages, view them as one
long scrollable page.

The data comes from the study pages that already exist, so the atlas can never
drift from them. Two page formats are in the repo and both are handled:

  overlay  the Exam 3 pages built here -- an unlabelled photo plus percent
           positioned label chips, which the atlas re-renders with the same
           layout script the study page uses
  image    the older Exam 2 pages and the original 17 -- a single pre-labelled
           jpg, which the atlas just shows

Grouping is lifted out of index.html so the atlas matches the homepage exactly
rather than reimplementing the classification.
"""
import html, json, os, re, sys
from PIL import Image

REPO = "/Users/jaxonluke/Developer/PA_Quizzes"
EXAMS = {"anatomy-practicum-exam2": ("Anatomy Practicum Exam 2", "Practicum Exam 2"),
         "anatomy-practicum-exam3": ("Anatomy Practicum Exam 3", "Practicum Exam 3")}


def container(h, examid):
    i = h.find(f'data-examid="{examid}"')
    if i < 0:
        return ""
    start = h.rfind("<details", 0, i)
    depth, j = 0, start
    while True:
        a, b = h.find("<details", j), h.find("</details>", j)
        if b < 0:
            return h[start:]
        if 0 <= a < b:
            depth += 1; j = a + 8
        else:
            depth -= 1; j = b + 10
            if depth == 0:
                return h[start:j]


def grouping(h):
    """slug -> (exam label, section, region), read off the homepage listing."""
    out = {}
    for examid, (folder, exam_label) in EXAMS.items():
        blk = container(h, examid)
        # walk the section/subgroup nesting, tracking the current headings
        section = region = None
        for m in re.finditer(
                r'<details class="topic-section" data-examid="([^"]+)">\s*'
                r'<summary><span>([^<]*)</span></summary>'
                r'|<li><a class="quiz-link" href="[^"]*?/([^"]+)-study\.html">', blk):
            if m.group(1):
                depth = m.group(1).count("-")
                label = html.unescape(m.group(2)).strip()
                # a subgroup id carries -exams-/-study- in it; a section id doesn't
                if "-exams-" in m.group(1) or "-study-" in m.group(1):
                    region = label
                else:
                    section, region = label, None
            elif m.group(3):
                out[m.group(3)] = (exam_label, section or "Other", region or "General")
    return out


def parse_study(path):
    """-> dict(kind, img, w, h, markers) for one study page."""
    h = open(path).read()
    d = os.path.dirname(path)
    labs = re.findall(
        r'<span class="pm-lab pm-[lr]" data-x="([-\d.]+)" data-y="([-\d.]+)">(.*?)</span>', h)
    if labs:
        m = re.search(r'<div class="pm-wrap"><img src="([^"]+)"', h)
        img = m.group(1) if m else None
        markers = [dict(x=float(x), y=float(y), t=html.unescape(t)) for x, y, t in labs]
        kind = "overlay"
    else:
        m = re.search(r'<div class="diagram-wrap">\s*<img src="([^"]+)"', h)
        img, markers, kind = (m.group(1) if m else None), [], "image"
    if not img:
        return None
    w = hgt = 0
    p = os.path.join(d, img)
    if os.path.exists(p):
        try:
            w, hgt = Image.open(p).size
        except Exception:
            pass
    title = ""
    tm = re.search(r"<h1>(.*?)</h1>", h, re.S)
    if tm:
        title = html.unescape(re.sub(r"<[^>]+>", "", tm.group(1))).strip()
        title = re.sub(r"\s*&mdash;.*$|\s*—\s*Study Reference$", "", title).strip()
    return dict(kind=kind, img=img, w=w, h=hgt, markers=markers, title=title)


def collect():
    idx = open(os.path.join(REPO, "index.html")).read()
    groups = grouping(idx)
    rows = []
    for examid, (folder, exam_label) in EXAMS.items():
        d = os.path.join(REPO, folder)
        for f in sorted(os.listdir(d)):
            if not f.endswith("-study.html"):
                continue
            slug = f[: -len("-study.html")]
            info = parse_study(os.path.join(d, f))
            if not info:
                continue
            exam, section, region = groups.get(slug, (exam_label, "Other", "General"))
            rows.append(dict(slug=slug, folder=folder, exam=exam, section=section,
                             region=region, **info))
    return rows


def main():
    rows = collect()
    out = os.path.join(REPO, "practicum-atlas-data.js")
    with open(out, "w") as fh:
        fh.write("/* Generated by tools/build_atlas.py -- do not hand-edit. */\n")
        fh.write("window.ATLAS = " + json.dumps(rows, separators=(",", ":")) + ";\n")
    size = os.path.getsize(out)
    from collections import Counter
    c = Counter((r["exam"], r["kind"]) for r in rows)
    print(f"atlas entries: {len(rows)}   data file {size/1024:.0f} KB")
    for k in sorted(c):
        print(f"  {k[0]:<20} {k[1]:<8} {c[k]}")
    missing = [r["slug"] for r in rows if not r["w"]]
    if missing:
        print(f"  !! {len(missing)} entries with no image dimensions: {missing[:4]}")
    unmapped = [r["slug"] for r in rows if r["section"] == "Other"]
    if unmapped:
        print(f"  !! {len(unmapped)} not found in the homepage listing: {unmapped[:4]}")


if __name__ == "__main__":
    main()
