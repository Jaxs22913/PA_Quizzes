/* On-demand loader for the Group Study question bank.

   The bank used to ship as one 5.8 MB group-questions.js that both group
   pages pulled in before anything could happen. It is now split into
   group-quizzes/index.js (a 38 KB manifest: title, class and question count,
   no question text) plus one chunk per quiz, fetched only when that quiz is
   actually picked or joined.

   Chunks assign into window.GROUP_QUIZZES, so every existing read of
   GROUP_QUIZZES[id] keeps working unchanged once the chunk has landed. */
(function () {
  var pending = {};   // id -> array of callbacks waiting on an in-flight load
  var failed = {};    // id -> true once a chunk has failed to load

  function chunkUrl(id) {
    // ids are generated by slug() in tools/build_group_quizzes.py: lowercase
    // alphanumerics and hyphens only, so they are safe as path segments.
    return "group-quizzes/" + encodeURIComponent(id) + ".js";
  }

  /* Loads one quiz's questions, then calls cb(quizOrNull). Safe to call for a
     quiz that is already loaded (fires cb immediately) or one that is already
     in flight (queues behind the existing request rather than re-fetching). */
  window.loadGroupQuiz = function (id, cb) {
    cb = cb || function () {};
    if (!id) { cb(null); return; }

    var bank = window.GROUP_QUIZZES || {};
    if (bank[id]) { cb(bank[id]); return; }
    // Remembering failures matters: callers retry by re-invoking themselves
    // from the callback, so without this a 404 or an offline fetch would spin
    // forever re-requesting the same missing chunk.
    if (failed[id]) { cb(null); return; }

    if (pending[id]) { pending[id].push(cb); return; }
    pending[id] = [cb];

    function done() {
      var q = (window.GROUP_QUIZZES || {})[id] || null;
      if (!q) failed[id] = true;
      var waiting = pending[id] || [];
      delete pending[id];
      for (var i = 0; i < waiting.length; i++) {
        try { waiting[i](q); } catch (e) {}
      }
    }

    var s = document.createElement("script");
    s.src = chunkUrl(id);
    s.async = false;
    s.onload = done;
    // A missing or failed chunk must still settle the callbacks with null --
    // otherwise the caller's spinner hangs forever with no explanation.
    s.onerror = done;
    document.head.appendChild(s);
  };

  /* The manifest is a plain deferred script, so it may not have executed yet
     when an inline block runs. Both pages need to wait for it before they can
     render a picker or resolve a room's quiz. */
  window.whenGroupIndex = function (cb) {
    if (window.GROUP_INDEX) { cb(window.GROUP_INDEX); return; }
    setTimeout(function () { window.whenGroupIndex(cb); }, 50);
  };
})();
